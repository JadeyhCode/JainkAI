#define N_TOPICS (sizeof TOPICS / sizeof TOPICS[0])

static void pat_topics(FILE *f) {
    for (size_t t = 0; t < N_TOPICS; ++t) {
        const Topic *T = &TOPICS[t];
        /* 显式话题标注：块内所有行都属于第 t+1 个话题。
         * 训练时会把块内转移边打上这个话题 id，生成时先投票选话题再只走该话题的边。 */
        say(f, "[话题:%zu]", t + 1);
        /* ① 每个问法 → 每条回复（主干边：输入尾词 → 回复首词） */
        for (int q = 0; q < 6; ++q) {
            if (!T->q[q]) continue;
            for (int r = 0; r < 20; ++r) {
                if (!T->r[r]) continue;
                say(f, "[原语:对象] %s [对话:结束] [原语:对象] %s [对话:结束]",
                    T->q[q], T->r[r]);
            }
        }
        /* ② 同话题的回复互为「输入」→ 让回复内部词共享出边，
         *    这是把角色子图铺密的关键（同一批词互相成边）。 */
        for (int a = 0; a < 20; ++a) {
            if (!T->r[a]) continue;
            for (int b = 0; b < 20; ++b) {
                if (a == b || !T->r[b]) continue;
                say(f, "[原语:对象] %s [对话:结束] [原语:对象] %s [对话:结束]",
                    T->r[a], T->r[b]);
            }
        }
        say(f, "[话题:0]");           /* 话题块结束 */
    }
}

/* 常见的「接话」短句：让回复开头之后还有高频的合法续接 */
static void pat_continuations(FILE *f) {
    static const char *openers[] = {
        "我", "你", "别", "那", "好", "很", "真", "没", "有", "谢谢", "当然", "可以",
        NULL
    };
    static const char *tails[] = {
        "会 一直 在 这里 陪 你 说 话", "很 高兴 你 愿意 和 我 说",
        "不 用 客气 这 是 我 该 做 的", "没 关系 我 不 着 急",
        "好 的 我 记 住 了", "谢 谢 你 告诉 我", "我 也 是 这样 想 的",
        "你 说 得 对", "我 明白 你 的 意思", "我 会 好好 想 一 想",
        "我 陪 你 一 起", "你 放心 我 在", NULL
    };
    for (size_t i = 0; openers[i]; ++i)
        for (size_t j = 0; tails[j]; ++j)
            say(f, "[原语:对象] %s [对话:结束] [原语:对象] %s %s [对话:结束]",
                openers[i], openers[i], tails[j]);
}

