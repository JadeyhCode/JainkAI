int main(int argc, char **argv) {
    FILE *f = stdout;
    if (argc > 1 && strcmp(argv[1], "-") != 0) {
        f = fopen(argv[1], "w");
        if (!f) { perror("fopen"); return 1; }
    }
    counter = 0x2545F491u;

    pat_greet(f);
    pat_self(f);
    pat_what(f);
    pat_why(f);
    pat_how(f);
    pat_where_who_when(f);
    pat_request(f);
    pat_social(f);
    pat_feel(f);
    pat_like(f);
    pat_cause(f);
    pat_capability(f);
    pat_react(f);
    pat_statement(f);
    pat_multi(f);
    pat_bridge(f);
    pat_topic_replies(f);
    pat_topics(f);
    pat_continuations(f);

    if (f != stdout) fclose(f);
    fprintf(stderr, "已生成 %zu 行对话语料\n", n_lines);
    return 0;
}
