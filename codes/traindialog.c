/* counter 是**伪随机数状态**（R() 用它抽词），不是行数。
 * 之前把 counter 当行数打出来，于是报出「已生成 1065968960397355650 行」这种数字 ——
 * 变量名和用途对不上，纯粹是打印错了。行数单独记。 */
static size_t counter = 0;
static size_t n_lines = 0;

/* 用取模做成确定性「伪随机」：同一份语料每次生成完全一样，方便复现 */
static unsigned pick(unsigned salt) {
    counter = counter * 1103515245u + 12345u + salt;
    return (unsigned)((counter >> 16) & 0x7fffffffu);
}
static const char *R(const char **arr, size_t n, unsigned salt) {
    return arr[pick(salt) % n];
}

/* 一句回复：组装 + 计数 */
static void say(FILE *f, const char *fmt, ...) {
    va_list ap;
    va_start(ap, fmt);
    vfprintf(f, fmt, ap);
    va_end(ap);
    fputc('\n', f);
    counter++;
    n_lines++;
}

