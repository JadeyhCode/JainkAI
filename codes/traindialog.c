/* traindialog.c — 对话语料生成器
 *
 * 编译：cc -O2 -o traindialog traindialog.c
 * 运行：./traindialog > dialog.txt     或     ./traindialog dialog.txt
 *
 * 为什么要它：原来的 seed*.txt 是「词与词共现」（`猫 → 动物`、`我 → 喜欢`），
 * 没有任何对话结构。于是生成器只能顺着输入的最后一个词往下滑 ——
 * 问「你是谁」它会顺着「谁」接一个「谁」，问「猫是什么」它接「猫是季节」。
 *
 * 这份语料补的是**多词序列**：`输入尾词 → 回复首词 → 回复次词 → …`。
 * 训练之后，从输入最后一个词出发的加权游走就能落到一条真实的回复上。
 *
 * 覆盖的对话场景：打招呼 / 自我介绍 / 提问三种（是什么·为什么·怎么·在哪·是谁·什么时候）/
 * 索取 / 道谢 / 道歉 / 道别 / 表达喜好与情绪 / 因果解释 / 能力与感知 / 时间 / 附和与否定 /
 * 追问 / 澄清。带 [原语:连接] 的地方是「一问一答」的边界。
 */
