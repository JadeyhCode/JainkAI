/* 打招呼 / 寒暄：用户说 A，AI 回 B */
static void pat_greet(FILE *f) {
    static const char *hi[]   = {"你好", "您好", "嗨", "早上好", "晚上好", "在吗"};
    static const char *hi_r[] = {"你好", "你好啊", "嗨", "我在", "我在的", "早上好",
                                 "晚上好", "很高兴见到你"};
    for (size_t i = 0; i < sizeof hi / sizeof hi[0]; ++i) {
        const char *r = R(hi_r, sizeof hi_r / sizeof hi_r[0], (unsigned)i * 7 + 1);
        say(f, "[原语:对象] %s [对话:结束] [原语:对象] %s [对话:结束]", hi[i], r);
    }
    /* 问候语后续 */
    static const char *after[] = {"你 好 吗", "你 最近 怎么样", "你 在 做什么",
                                  "今天 过得 怎么样"};
    static const char *after_r[] = {"我 很 好", "我 很 好 谢谢", "我 在 想 事情",
                                    "我 在 学习", "今天 我 很 开心", "我 也 很 好"};
    for (size_t i = 0; i < sizeof after / sizeof after[0]; ++i) {
        const char *r = R(after_r, sizeof after_r / sizeof after_r[0], (unsigned)i * 11 + 3);
        say(f, "[原语:对象] %s [对话:结束] [原语:对象] %s [对话:结束]", after[i], r);
    }
}

