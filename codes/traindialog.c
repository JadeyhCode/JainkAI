/* 提问：是什么 */
static void pat_what(FILE *f) {
    static const char *essence[] = {"是 一种 动物", "是 一种 东西", "是 一种 植物",
                                    "是 一种 食物", "是 一种 地方", "是 一个 名字",
                                    "是 我 认识 的 东西", "是 我 不 太 确定 的 东西"};
    static const char *trait[]   = {"它 很 大", "它 很 小", "它 很 好", "它 很 快",
                                    "它 会 动", "它 很 安静", "它 很 热闹",
                                    "它 和 人 很 近"};
    for (size_t i = 0; i < N_THING; ++i) {
        const char *x = THING[i];
        const char *e = R(essence, sizeof essence / sizeof essence[0], (unsigned)i + 5);
        const char *t = R(trait, sizeof trait / sizeof trait[0], (unsigned)i * 3 + 7);
        say(f, "[原语:对象] %s 是 什么 [原语:连接] [原语:对象] %s %s [原语:连接]", x, x, e);
        say(f, "[原语:对象] %s 是 什么样 的 [原语:连接] [原语:对象] %s [原语:连接]", x, t);
        say(f, "[原语:对象] 什么 是 %s [原语:连接] [原语:对象] %s 就是 %s [原语:连接]",
            x, x, e + 2);   /* 跳过「是 一种」取宾语 */
    }
}

/* 提问：为什么 */
static void pat_why(FILE *f) {
    static const char *reasons[] = {
        "因为 它 需要 食物", "因为 它 想 活 下去", "因为 它 喜欢 这样",
        "因为 它 怕 危险", "因为 它 在 学习", "因为 它 想 和 你 在 一起",
        "因为 它 累 了", "因为 它 很 好奇",
    };
    for (size_t i = 0; i < N_SUBJ; ++i) {
        for (size_t j = 0; j < N_VERB; ++j) {
            if ((i + j) % 3) continue;
            const char *s = SUBJ[i], *v = VERB[j];
            const char *r = R(reasons, sizeof reasons / sizeof reasons[0],
                              (unsigned)(i * 31 + j * 7));
            say(f, "[原语:对象] %s 为什么 %s [原语:连接] [原语:对象] %s [原语:连接]",
                s, v, r);
        }
    }
    static const char *common[] = {"为什么 天 是 蓝 的", "为什么 你 会 说话",
                                   "为什么 我 会 忘"};
    static const char *common_r[] = {"因为 光 在 空气 里 散开",
                                     "因为 我 学过 很多 句子",
                                     "因为 记忆 会 慢慢 变 淡"};
    for (size_t i = 0; i < sizeof common / sizeof common[0]; ++i)
        say(f, "[原语:对象] %s [对话:结束] [原语:对象] %s [对话:结束]",
            common[i], common_r[i]);
}

